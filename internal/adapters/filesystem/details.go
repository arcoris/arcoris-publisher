package filesystem

// porterrDetails builds small non-secret detail maps for structured errors.
//
// Odd trailing values are ignored deliberately so call sites can pass compact
// key/value lists without needing local map construction.
func porterrDetails(kv ...string) map[string]string {
	m := map[string]string{}
	for i := 0; i+1 < len(kv); i += 2 {
		m[kv[i]] = kv[i+1]
	}
	return m
}
